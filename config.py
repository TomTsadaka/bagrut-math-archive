def questionnaire_meta(code: str) -> dict:
    """מחזיר מטא-דאטה לשאלון; מנחש לפי תבנית אם לא מוכר."""
    code = str(code).lstrip("0")
    if code in QUESTIONNAIRES:
        return dict(QUESTIONNAIRES[code], code=code, known=True)
    guess = {"units": None, "program": "לא ידוע", "part": None,
             "desc": f"שאלון {code}", "code": code, "known": False}
    if len(code) == 5 and code.startswith("35"):
        d3 = code[2]  # 1/3 -> 3 יח"ל, 2/4 -> 4, 5 -> 5
        guess["units"] = {"1": 3, "3": 3, "2": 4, "4": 4, "5": 5}.get(d3)
        guess["part"] = 1 if code.endswith("1") else (2 if code.endswith("2") else None)
    return guess

