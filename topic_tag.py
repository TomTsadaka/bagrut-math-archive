THRESHOLD = 2      # סף ניקוד לתיוג
MAX_TAGS = 3


def tag(text):
    if not text:
        return []
    scores = {}
    for topic, words in KW.items():
        sc = sum(w for w, kw in words if kw in text)
        if sc >= THRESHOLD:
            scores[topic] = sc
    return [t for t, _ in sorted(scores.items(), key=lambda kv: -kv[1])[:MAX_TAGS]]


def run():
    path = os.path.join(os.path.dirname(__file__), "site", "data", "scans.json")
    scans = json.load(open(path, encoding="utf-8"))
    stats = collections.Counter(); none = 0; ntags = collections.Counter()
    for s in scans:
        t = tag(s.get("text", ""))
        s["topics"] = t
        ntags[len(t)] += 1
        if not t:
            none += 1
        for x in t:
            stats[x] += 1
    json.dump(scans, open(path, "w", encoding="utf-8"),
              ensure_ascii=False, separators=(",", ":"))
    tot = len(scans)
    print(f"תויגו {tot-none}/{tot} ({(tot-none)/tot:.0%}), ללא תיוג {none}")
    print("מספר תגיות לשאלה:", dict(sorted(ntags.items())))
    print()
    for k, v in stats.most_common():
        print(f"  {k}: {v}")
    return scans


if __name__ == "__main__":
    run()
