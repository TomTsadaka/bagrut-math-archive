THRESHOLD = 3
MAX_TAGS = 3   # בפועל מוגבל גם ביחס הניקוד


# כותרת פרק שדלפה לתחילת חיתוך השאלה — היא גם אות לנושא וגם מקור לרעש
LEAK = re.compile(
    r'^\s*(?:פרק\s+\S+\s*[–—-]?\s*)?('
    r'חשבון\s+דיפרנציאלי[^.]{0,60}|אלגברה\s*(?:והסתברות)?|גאומטרי[^.]{0,50}|'
    r'גיאומטרי[^.]{0,50}|סדרות[^.]{0,40}|הסתברות|סטטיסטיקה[^.]{0,30}|'
    r'אשכול\s+\S+(?:\s+\S+){0,3}|גדילה\s+ודעיכה[^.]{0,40}'
    r')')


def split_leak(text):
    """מפריד כותרת פרק שדלפה מגוף השאלה."""
    m = LEAK.match(text or "")
    if not m:
        return None, text
    return m.group(1).strip(), (text or "")[m.end():]


def _has(text, kw):
    """הטקסט המחולץ שומר מילים תקינות אך הופך את סדרן.

    לכן ביטוי נבדק גם כסדרו וגם הפוך — ולא כקבוצת מילים מפוזרת,
    שהייתה מתאימה למילים במקומות שונים לגמרי בשאלה.
    """
    if " " not in kw:
        return kw in text
    if kw in text:
        return True
    return " ".join(reversed(kw.split())) in text


def chapter_topics(chapter):
    """קבוצת הנושאים שהפרק מתיר. None = פרק מעורב, בלי הגבלה."""
    if not chapter:
        return "NONE"
    allowed = []
    analytic = bool(re.search(r'אנליטי', chapter))
    for pat, topics in CHAPTER_RULES:
        if not re.search(pat, chapter):
            continue
        if topics is None:
            return None                           # שאלות קצרות
        # "גאומטרייה אנליטית" אינה גיאומטריית המישור
        if analytic and pat.startswith(r'גאומטרי'):
            continue
        for t in topics:
            if t not in allowed:
                allowed.append(t)
    return allowed or "NONE"


def tag(text, chapter=None):
    leaked, body = split_leak(text)
    # אם לא שויך פרק, הכותרת שדלפה לחיתוך היא המקור הבא בתוקפו
    if not chapter and leaked:
        chapter = leaked
    allowed = chapter_topics(chapter)
    text = body
    pool = KW if allowed in (None, "NONE") else {k: v for k, v in KW.items() if k in allowed}
    scores = {}
    for topic, words in pool.items():
        sc = sum(w for w, kw in words if _has(text or "", kw))
        if sc >= THRESHOLD:
            scores[topic] = sc
    if scores:
        ranked = sorted(scores.items(), key=lambda kv: -kv[1])
        top = ranked[0][1]
        keep = [t for t, sc in ranked if sc >= top * 0.6][:MAX_TAGS]
        # שאלה במערכת צירים אינה גם גיאומטריית מישור
        if "גיאומטריה אנליטית" in keep and "גיאומטריה" in keep:
            keep.remove("גיאומטריה")
        return keep
    # אין מילת מפתח מכרעת — נשענים על הצהרת הפרק
    if isinstance(allowed, list) and allowed:
        return allowed[:2]
    return []


def run():
    base = os.path.dirname(__file__)
    idx = json.load(open(os.path.join(base, "data", "cropped_questions.json"), encoding="utf-8"))
    stats = collections.Counter(); none = 0; tot = 0; from_ch = 0
    for qs in idx.values():
        for q in qs:
            tot += 1
            t = tag(q.get("text", ""), q.get("chapter"))
            q["topics"] = t
            if not t:
                none += 1
            if q.get("chapter"):
                from_ch += 1
            for x in t:
                stats[x] += 1
    json.dump(idx, open(os.path.join(base, "data", "cropped_questions.json"), "w",
                        encoding="utf-8"), ensure_ascii=False)
    print(f"תויגו {tot-none}/{tot} ({(tot-none)/tot:.0%}) | מתוכן {from_ch} עם פרק רשמי")
    for k, v in stats.most_common():
        print(f"  {k}: {v}")
    return idx


if __name__ == "__main__":
    run()
